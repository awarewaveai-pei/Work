#!/usr/bin/env bash
# Wire the governance hook runner into a REMOTE Claude Code session container.
#
# Why this exists: on the two Windows workstations, hooks are wired through
# ~/.claude/settings.json (generated from mcp/claude-userlevel/settings.template.json
# by sync-claude-userlevel.ps1). Remote containers (Claude Code on the web /
# GitHub Actions) have no user-level settings, so without this file every
# remote session runs with ZERO mechanical gates (finding: 2026-07-02 audit).
#
# This script writes .claude/settings.local.json (gitignored — it must NEVER
# be tracked: on the workstations repo/.claude is a junction to ~/.claude, so
# a tracked settings file would collide with the user-level one).
#
# Usage:
#   bash scripts/wire-remote-hooks.sh          # refuses to overwrite an existing file
#   bash scripts/wire-remote-hooks.sh --force  # overwrite
#
# Register it as the environment's setup script (Claude Code web → environment
# settings) so it runs before each session starts; hooks are snapshotted at
# session startup, so wiring mid-session does not arm them.
set -euo pipefail

REPO_ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
TARGET="$REPO_ROOT/.claude/settings.local.json"
RUNNER="\$CLAUDE_PROJECT_DIR/mcp/claude-userlevel/hooks/runner.js"

if [[ -f "$TARGET" && "${1:-}" != "--force" ]]; then
  if grep -q 'hooks/runner.js' "$TARGET"; then
    echo "wire-remote-hooks: runner already wired in $TARGET — nothing to do."
    exit 0
  fi
  echo "wire-remote-hooks: $TARGET exists without runner wiring. Re-run with --force to overwrite." >&2
  exit 1
fi

mkdir -p "$REPO_ROOT/.claude"
cat > "$TARGET" <<JSON
{
  "_comment": "GENERATED by scripts/wire-remote-hooks.sh — do not edit by hand, do not commit (gitignored). Wires the governance runner (mcp/claude-userlevel/hooks/runner.js + rules.manifest.json) into remote sessions.",
  "permissions": {
    "_deny_comment": "Mirror of the Workflow + Perplexity-chat entries of permissions.deny in mcp/claude-userlevel/settings.template.json — Workflow fan-out is invisible to PreToolUse hooks (2026-09-03: 99 agents, quota gone); Perplexity is Search-API only (chat tools drained the account 2026-06-21 and 2026-09-12). tests/hooks/settings-deny-parity.test.mjs enforces the mirror.",
    "deny": [ "Workflow", "mcp__perplexity__perplexity_ask", "mcp__perplexity__perplexity_reason", "mcp__perplexity__perplexity_research" ]
  },
  "hooks": {
    "UserPromptSubmit": [
      { "matcher": ".*", "hooks": [ { "type": "command", "command": "node \"$RUNNER\" UserPromptSubmit", "timeout": 15 } ] }
    ],
    "PreToolUse": [
      { "matcher": ".*", "hooks": [ { "type": "command", "command": "node \"$RUNNER\" PreToolUse", "timeout": 60 } ] }
    ],
    "PostToolUse": [
      { "matcher": ".*", "hooks": [ { "type": "command", "command": "node \"$RUNNER\" PostToolUse", "timeout": 90 } ] }
    ],
    "PostToolUseFailure": [
      { "matcher": ".*", "hooks": [ { "type": "command", "command": "node \"$RUNNER\" PostToolUseFailure", "timeout": 30 } ] }
    ],
    "Stop": [
      { "matcher": "*", "hooks": [ { "type": "command", "command": "node \"$RUNNER\" Stop", "timeout": 300 } ] }
    ],
    "SessionStart": [
      { "matcher": "startup|resume", "hooks": [ { "type": "command", "command": "node \"$RUNNER\" SessionStart", "timeout": 15 } ] }
    ],
    "SubagentStart": [
      { "matcher": ".*", "hooks": [ { "type": "command", "command": "node \"$RUNNER\" SubagentStart", "timeout": 15 } ] }
    ]
  }
}
JSON

node -e "JSON.parse(require('fs').readFileSync(process.argv[1],'utf8'))" "$TARGET" \
  && echo "wire-remote-hooks: wrote $TARGET (valid JSON). Hooks arm at next session start."
