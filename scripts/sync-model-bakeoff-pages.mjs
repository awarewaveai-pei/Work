#!/usr/bin/env node
// Copies the three model bake-off pages from agency-os/reports/model-bakeoff/ (the source) into next-admin's
// content/model-bakeoff/<slug>/index.html, which the staff-only route /tools/ai-models/bakeoff/<slug> serves
// (sg-deploy ships apps/next-admin only, so agency-os/reports/ never reaches the host). Re-run after a re-test.
//   node scripts/sync-model-bakeoff-pages.mjs          write the three files
//   node scripts/sync-model-bakeoff-pages.mjs --check  exit 1 when a file differs from what this script would write
// The article page fetch()es articles.json next to it; a sandboxed iframe has no same-origin sibling to fetch, so the
// JSON is inlined here. Pages published as claude.ai artifacts have no doctype/charset: a minimal skeleton is prepended.
import { readFileSync, writeFileSync, mkdirSync, existsSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const SRC = path.join(ROOT, "agency-os/reports/model-bakeoff");
const OUT = path.join(ROOT, "lobster-factory/infra/hetzner-phase1-core/apps/next-admin/content/model-bakeoff");
const SCRIPT = "scripts/sync-model-bakeoff-pages.mjs";

// slug -> source page; the slugs are the fixed list in app/(shell)/tools/ai-models/bakeoff-pages.ts
const PAGES = {
  article: "2026-11-article/article-bakeoff.html",
  copy: "2026-11-copy/copy-bakeoff.html",
  image: "2026-11-article-image/image-bakeoff.html",
};

const FETCH_CALL = 'fetch("articles.json").then((r) => r.json())';

function inlineArticles(html, dir) {
  if (!html.includes(FETCH_CALL)) throw new Error(`article page: expected ${FETCH_CALL} -- the page changed, update this script`);
  // < keeps "</script>" or "<!--" inside an article from ending the script element
  const json = readFileSync(path.join(dir, "articles.json"), "utf8").trim().replace(/</g, "\\u003c");
  return html.replace(FETCH_CALL, () => `Promise.resolve(${json})`);
}

function build(slug) {
  const rel = PAGES[slug];
  const file = path.join(SRC, rel);
  let html = readFileSync(file, "utf8");
  if (slug === "article") html = inlineArticles(html, path.dirname(file));
  const note = `<!-- Generated by ${SCRIPT} from agency-os/reports/model-bakeoff/${rel}; edit the source and re-run, not this file. -->\n`;
  const m = /^\s*<!doctype html>/i.exec(html);
  if (m) return m[0].trimStart() + "\n" + note + html.slice(m[0].length).replace(/^\n/, "");
  return `<!doctype html>\n${note}<meta charset="utf-8">\n<meta name="viewport" content="width=device-width, initial-scale=1">\n${html}`;
}

const check = process.argv.includes("--check");
let stale = 0;
for (const slug of Object.keys(PAGES)) {
  const html = build(slug);
  const target = path.join(OUT, slug, "index.html");
  if (check) {
    const same = existsSync(target) && readFileSync(target, "utf8") === html;
    if (!same) { stale += 1; console.error(`stale: ${path.relative(ROOT, target)} -- run node ${SCRIPT}`); }
    continue;
  }
  mkdirSync(path.dirname(target), { recursive: true });
  writeFileSync(target, html, "utf8");
  console.log(`wrote ${path.relative(ROOT, target)} (${Buffer.byteLength(html)} bytes)`);
}
if (check) { if (stale) process.exit(1); console.log("ok: 3 pages match their source"); }
