#!/usr/bin/env node
// Generates the every-turn trigger index inside agency-os/AGENTS.md from the lookup tables in
// agency-os/docs/operations/TOOL_TRIGGER_MAP.md.
//
// Why: the five lookup tables (88 rows) left AGENTS.md in the 2026-09-04 slim. AGENTS.md kept one
// sentence -- "if the user's words hit a trigger, follow the map" -- which cannot be acted on,
// because an agent that has not opened the map cannot know a trigger was hit. Rows backed by a
// hook, or by a command / agent / skill whose description the harness loads every session, still
// reach the agent; the rest were knowable only by opening the file (operator, 2026-10-01: "I do
// not want a Claude with half a brain").
//
// What: one line per row that nothing else brings into context -- trigger -> where to look.
// The map stays the only place a row is written; this block is derived from it and
// scripts/verify-governance-pointers.mjs fails when the two differ, so they cannot drift.
//
// Row selection (deterministic):
//   symptom -> runbook table      every row
//   self-trigger table            every row without a hook marker (the trigger is what the agent
//   task-type preload table       every row                        is doing, no description fires)
//   phrase table                  rows without a hook marker whose target is not a loaded
//                                 command / agent / skill
//   work-type -> agent table      none (each agent's own description carries its triggers)
//
// Usage: node scripts/gen-trigger-index.mjs            print the block
//        node scripts/gen-trigger-index.mjs --write    rewrite the block in AGENTS.md
//        node scripts/gen-trigger-index.mjs --check    exit 1 when AGENTS.md is out of date

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const SELF = fileURLToPath(import.meta.url);
const DEFAULT_ROOT = path.resolve(path.dirname(SELF), '..');

export const MAP_REL = 'agency-os/docs/operations/TOOL_TRIGGER_MAP.md';
export const AGENTS_REL = 'agency-os/AGENTS.md';
export const BEGIN = '<!-- TRIGGER-INDEX:BEGIN generated by scripts/gen-trigger-index.mjs from docs/operations/TOOL_TRIGGER_MAP.md; edit the map, then run --write -->';
export const END = '<!-- TRIGGER-INDEX:END -->';

const MAP_SECTION = '## AGENTS.md 觸發與路由正本';
const HOOK_MARK = '\u{1F527}';
const BACKSLASH = String.fromCharCode(92);
const MAX_TRIGGER = 46;
const MAX_TARGET = 72;

// Table heading (start of the "### " line) -> how its rows are selected and labelled.
const TABLES = [
  { head: '問題症狀 → Runbook 路由表', label: '症狀 → 先讀 runbook', mode: 'all' },
  { head: 'Claude 工作自觸發規則', label: '我正在做 X → 接著做', mode: 'no-hook', targets: 3 },
  { head: '任務到達協議 步驟 2', label: '任務類型 → 先載入', mode: 'all', preload: true, targets: 2 },
  { head: '代理自動工具使用規則', label: '使用者提到 → 先讀／先跑', mode: 'unloaded' },
  // Not indexed (each agent's own description carries its triggers), but it must still be there:
  // a map that lost one of its five tables has been restructured and the selection rules need a look.
  { head: '工作類型 → Agent/Tool 路由表', mode: 'none' },
];

const strip = (text) => (text.charCodeAt(0) === 0xfeff ? text.slice(1) : text);

/** Split one markdown table row into cells; a pipe inside a code span or escaped stays in the cell. */
export function splitRow(line) {
  // Code spans: a run of N backticks closes at the next run of exactly N (so ``a|b`` is one span).
  const runs = [...line.matchAll(/`+/g)].map((m) => ({ at: m.index, len: m[0].length }));
  const spans = [];
  for (let i = 0; i < runs.length; i++) {
    const j = runs.findIndex((r, k) => k > i && r.len === runs[i].len);
    if (j === -1) continue;
    spans.push([runs[i].at, runs[j].at + runs[j].len]);
    i = j;
  }
  const inCode = (i) => spans.some(([a, b]) => i > a && i < b);
  const cells = [];
  let cur = '';
  for (let i = 1; i < line.length; i++) {
    const c = line[i];
    if (c === BACKSLASH && line[i + 1] === '|') {
      cur += '|';
      i += 1;
      continue;
    }
    if (c === '|' && !inCode(i)) {
      cells.push(cur.trim());
      cur = '';
      continue;
    }
    cur += c;
  }
  if (cur.trim() !== '') cells.push(cur.trim());
  return cells;
}

const clip = (s, max) => (s.length > max ? `${s.slice(0, max - 1)}…` : s);

function targetsOf(action) {
  const out = [];
  const re = /`([^`]+)`|\]\(([^)]+)\)/g;
  for (const m of action.matchAll(re)) {
    const t = m[1] !== undefined ? m[1] : m[2].split('/').pop();
    if (t && !out.includes(t)) out.push(t);
  }
  return out;
}

/**
 * Pure: map text + the set of loaded command/agent/skill names -> the index block body (no markers).
 * Throws when the map no longer has the section or a table it is built from, so a restructured map
 * cannot quietly produce an empty index.
 */
export function renderIndex(mapText, loadedNames) {
  const lines = strip(mapText).split(/\r?\n/);
  const start = lines.findIndex((l) => l.startsWith(MAP_SECTION));
  if (start === -1) throw new Error(`${MAP_REL}: section "${MAP_SECTION}" not found`);
  let end = lines.findIndex((l, i) => i > start && l.startsWith('## '));
  if (end === -1) end = lines.length;

  const out = [];
  for (const table of TABLES) {
    const h = lines.findIndex((l, i) => i > start && i < end && l.startsWith(`### ${table.head}`));
    if (h === -1) throw new Error(`${MAP_REL}: table "### ${table.head}" not found`);
    // A table is: header row, separator row, then data rows up to the first blank line. Anything else
    // (no separator, a row without its leading pipe, a one-cell row) is an error -- never a skipped row.
    let sep = -1;
    for (let i = h + 1; i < end && !lines[i].startsWith('### '); i++) {
      if (/^\|[\s:|-]*-[\s:|-]*\|?\s*$/.test(lines[i])) {
        sep = i;
        break;
      }
    }
    if (sep === -1 || !lines[sep - 1].startsWith('|') || sep - 1 === h) {
      throw new Error(`${MAP_REL}: table "### ${table.head}" has no header row followed by a separator row`);
    }
    if (table.mode === 'none') continue;
    const rows = [];
    for (let i = sep + 1; i < end; i++) {
      const l = lines[i];
      if (l.trim() === '' || l.startsWith('#')) break;
      if (!l.startsWith('|')) throw new Error(`${MAP_REL}:${i + 1}: table row does not start with a pipe`);
      const cells = splitRow(l);
      if (cells.length < (table.preload ? 3 : 2)) throw new Error(`${MAP_REL}:${i + 1}: table row has too few cells`);
      const action = cells.slice(table.preload ? 2 : 1).join(' ');
      if (table.mode !== 'all' && action.includes(HOOK_MARK)) continue;
      const targets = targetsOf(action);
      // A target is a "tool" when it names a loaded command / agent / skill (`/health`, `critic`, `wordpress-*`).
      const isTool = (t) => {
        const n = t.replace(/^\//, '').split(/[ <]/)[0];
        if (loadedNames.has(n)) return true;
        // `wordpress-*` is a family of loaded agents; a bare glob like `v*` (a tag pattern) is not
        return n.endsWith('-*') && [...loadedNames].some((x) => x.startsWith(n.slice(0, -1)));
      };
      if (table.mode === 'unloaded') {
        // Skip a row the harness already surfaces: its first step is a loaded tool, or the trigger itself
        // is a slash command. A row whose first step is "read this file" stays, whatever comes after.
        if (targets.length === 0 || isTool(targets[0]) || targetsOf(cells[0]).some(isTool)) continue;
      }
      let trigger = cells[0]
        .replace(/\*\*/g, '')
        .replace(/`/g, '')
        .replace(/^使用者(提到|說|問|要)?/, '')
        .replace(/」\s*[\/／]?\s*「/g, '／')
        .replace(/[「」]/g, '')
        .trim();
      if (table.preload) trigger = `${trigger}（${cells[1]}）`;
      // Multi-step rows (self-trigger, preload) list their tools in order; other rows show the first target.
      const tools = table.targets ? targets.filter(isTool) : [];
      const shown = (tools.length ? tools : targets).slice(0, table.targets || 1).map((t) => `\`${clip(t, MAX_TARGET)}\``).join(' → ');
      rows.push(`- ${clip(trigger, MAX_TRIGGER)} → ${shown || clip(action.replace(/\*\*/g, ''), MAX_TARGET)}`);
    }
    if (rows.length === 0) throw new Error(`${MAP_REL}: table "### ${table.head}" produced no index rows`);
    out.push(`**${table.label}**（${rows.length}）`, ...rows);
  }
  return out.join('\n');
}

/** Names whose descriptions the harness loads every session. */
export function loadedNames(root = DEFAULT_ROOT) {
  const names = new Set();
  for (const dir of ['.claude/commands', '.claude/agents']) {
    for (const f of fs.readdirSync(path.join(root, dir))) if (f.endsWith('.md')) names.add(f.slice(0, -3));
  }
  for (const e of fs.readdirSync(path.join(root, '.claude/skills'), { withFileTypes: true })) if (e.isDirectory()) names.add(e.name);
  return names;
}

export function expectedBlock(root = DEFAULT_ROOT) {
  const map = fs.readFileSync(path.join(root, MAP_REL), 'utf8');
  return `${BEGIN}\n${renderIndex(map, loadedNames(root))}\n${END}`;
}

/**
 * The block currently in AGENTS.md (markers included, newlines normalised). null unless there is exactly
 * one BEGIN followed by exactly one END: a second (stale) copy of the block must not hide behind the first.
 */
export function currentBlock(agentsText) {
  const t = strip(agentsText).replace(/\r\n/g, '\n');
  const a = t.indexOf(BEGIN);
  const b = t.indexOf(END);
  if (a === -1 || b === -1 || b < a) return null;
  if (t.indexOf(BEGIN, a + 1) !== -1 || t.indexOf(END, b + 1) !== -1) return null;
  return t.slice(a, b + END.length);
}

function main() {
  const root = DEFAULT_ROOT;
  const expected = expectedBlock(root);
  const agentsPath = path.join(root, AGENTS_REL);
  const raw = fs.readFileSync(agentsPath, 'utf8');
  const have = currentBlock(raw);
  if (process.argv.includes('--check')) {
    if (have === expected) {
      console.log(`Trigger index up to date (${expected.split('\n').filter((l) => l.startsWith('- ')).length} rows).`);
      return 0;
    }
    console.error(have === null ? `${AGENTS_REL}: trigger index block is missing or duplicated (need exactly one BEGIN/END pair)` : `${AGENTS_REL}: trigger index differs from ${MAP_REL} -- run: node scripts/gen-trigger-index.mjs --write`);
    return 1;
  }
  if (process.argv.includes('--write')) {
    if (have === null) {
      console.error(`${AGENTS_REL}: need exactly one BEGIN/END marker pair -- place "${BEGIN}" and "${END}" where the index belongs, then re-run`);
      return 1;
    }
    const nl = raw.includes('\r\n') ? '\r\n' : '\n';
    const norm = raw.replace(/\r\n/g, '\n');
    const a = norm.indexOf(BEGIN);
    const b = norm.indexOf(END) + END.length;
    fs.writeFileSync(agentsPath, (norm.slice(0, a) + expected + norm.slice(b)).replace(/\n/g, nl));
    console.log(`Trigger index written (${Buffer.byteLength(expected)} bytes).`);
    return 0;
  }
  console.log(expected);
  return 0;
}

const invokedDirectly = Boolean(process.argv[1]) && path.resolve(process.argv[1]) === path.resolve(SELF);
if (invokedDirectly) process.exit(main());
