#!/usr/bin/env python3
"""Generate (or --check) two derived indexes so a session can locate a shape or a mother-document
section WITHOUT reading a 900-line schema or grepping an 87 KB document each time.

  docs/architecture/SPEC_QUICKREF.md          -- every specs/**/*.yaml + policies/**/*.yaml that carries an $id:
                                                 status, version, top-level named shapes, each shape's `required`
  docs/architecture/MOTHER_DOC_SECTION_INDEX.md -- every `#`/`##`/`###` heading of the three mother documents
                                                 with its CURRENT line number (so contracts can cite by
                                                 section and a reader can still jump to the line)

Both files are GENERATED. Never hand-edit them; re-run this script. `--check` exits 1 when either file
is stale (run by tests/run_golden_tests.py check family 6, so drift is loud, not silent).

Usage:  python tests/gen_spec_index.py          # (re)write both files
        python tests/gen_spec_index.py --check  # verify they match the current corpus
"""
import glob
import os
import re
import sys

import yaml

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT_DIR = os.path.join(ROOT, "docs", "architecture")
QUICKREF = os.path.join(OUT_DIR, "SPEC_QUICKREF.md")
SECTION_INDEX = os.path.join(OUT_DIR, "MOTHER_DOC_SECTION_INDEX.md")
MOTHER_DOCS = [
    "AI_LEGO_Cognitive_Engineering_Os_Global_Master_Plan_v1.md",
    "AI_LEGO_Cognitive_Engineering_Os_Global_Execution_Contract_v1.md",
    "AI_LEGO_Cognitive_Method_Atlas_Global_Architecture_v1.md",
]
# Top-level keys that are documentation or JSON-Schema keywords, not named shapes.
META_KEYS = {
    "$schema", "$id", "title", "version", "status", "description", "source_of_truth_for", "decided_by",
    "compilation_decisions", "worked_example", "worked_examples", "constraints", "referenced_by",
    "open_questions", "verification", "field_mapping", "task_context_only_fields", "duplicate_resolutions",
    "reference_vocabulary", "status_codes", "definitions", "properties", "required", "type", "allOf", "anyOf",
    "oneOf", "if", "then", "else", "examples", "default", "enum", "pattern", "items", "additionalProperties",
    "seed_content", "allowlist_registry", "migration_crosswalk", "id_grammar_conformance_examples",
}


def _shape_summary(node):
    """One line for a node that looks like a JSON-Schema shape; None otherwise."""
    if not isinstance(node, dict):
        return None
    if not (set(node) & {"type", "properties", "required", "$ref", "enum", "allOf", "oneOf", "anyOf", "const"}):
        return None
    parts = []
    if "type" in node:
        parts.append(f"type={node['type']}")
    if "$ref" in node:
        parts.append(f"$ref={node['$ref']}")
    if "enum" in node:
        parts.append(f"enum[{len(node['enum'])}]")
    if isinstance(node.get("required"), list):
        parts.append("required=[" + ", ".join(map(str, node["required"])) + "]")
    if isinstance(node.get("properties"), dict):
        parts.append(f"properties[{len(node['properties'])}]")
    if "allOf" in node:
        parts.append(f"allOf[{len(node['allOf'])}]")
    return " ".join(parts)


def build_quickref():
    lines = [
        "# SPEC_QUICKREF (generated)",
        "",
        "> GENERATED by `tests/gen_spec_index.py` -- do not hand-edit. `python tests/gen_spec_index.py --check` fails when stale.",
        "> One row per file under `specs/**` and `policies/**` that carries an `$id`. The last column lists the top-level named",
        "> shapes a fixture `target_ref` or a runtime `SchemaContracts.validate(...)` can point at; a file that validates at its",
        "> own root shows `(root)`. Read the file itself only when you are about to change it or validate against it.",
        "",
        "| file | status | version | shapes (`#/name`: summary) |",
        "|---|---|---|---|",
    ]
    files = sorted(
        glob.glob(os.path.join(ROOT, "specs", "**", "*.yaml"), recursive=True)
        + glob.glob(os.path.join(ROOT, "policies", "**", "*.yaml"), recursive=True)
    )
    for path in files:
        rel = os.path.relpath(path, ROOT).replace("\\", "/")
        with open(path, encoding="utf-8") as handle:
            try:
                doc = yaml.safe_load(handle)
            except yaml.YAMLError as error:
                lines.append(f"| `{rel}` | PARSE_ERROR | | {str(error).splitlines()[0]} |")
                continue
        if not isinstance(doc, dict) or "$id" not in doc:
            continue
        shapes = []
        root_summary = _shape_summary(doc)
        if root_summary:
            shapes.append(f"`(root)`: {root_summary}")
        for key, node in doc.items():
            if key in META_KEYS:
                continue
            summary = _shape_summary(node)
            if summary:
                shapes.append(f"`#/{key}`: {summary}")
        if isinstance(doc.get("definitions"), dict):
            for key, node in doc["definitions"].items():
                summary = _shape_summary(node)
                if summary:
                    shapes.append(f"`#/definitions/{key}`: {summary}")
        if isinstance(doc.get("reference_vocabulary"), dict):
            for key, node in doc["reference_vocabulary"].items():
                if isinstance(node, dict) and isinstance(node.get("schema"), dict):
                    shapes.append(f"`#/reference_vocabulary/{key}/schema`: {_shape_summary(node['schema'])}")
        cell = "<br>".join(shapes).replace("|", "\\|") if shapes else "(no top-level shapes; data/registry file)"
        lines.append(f"| `{rel}` | {doc.get('status', '')} | {doc.get('version', '')} | {cell} |")
    lines.append("")
    return "\n".join(lines)


def build_section_index():
    lines = [
        "# MOTHER_DOC_SECTION_INDEX (generated)",
        "",
        "> GENERATED by `tests/gen_spec_index.py` -- do not hand-edit. `python tests/gen_spec_index.py --check` fails when stale.",
        "> Cite mother documents by SECTION (e.g. `MP §8.4`) in contracts and ADRs; use this table to jump to the current",
        "> line. Line numbers are refreshed every time the script runs, so they never silently drift the way a",
        "> hand-typed `L724` does. Headings inside code fences are skipped.",
        "",
    ]
    heading = re.compile(r"^(#{1,3})\s+(.*\S)\s*$")
    for name in MOTHER_DOCS:
        path = os.path.join(ROOT, name)
        lines.append(f"## {name}")
        lines.append("")
        lines.append("| line | heading |")
        lines.append("|---|---|")
        with open(path, encoding="utf-8") as handle:
            in_fence = False
            for number, text in enumerate(handle, start=1):
                stripped = text.rstrip("\n")
                if stripped.startswith("```"):
                    in_fence = not in_fence
                    continue
                if in_fence:
                    continue
                match = heading.match(stripped)
                if match:
                    level = len(match.group(1))
                    title = match.group(2).replace("|", "\\|")
                    lines.append(f"| {number} | {'&nbsp;&nbsp;' * (level - 1)}{title} |")
        lines.append("")
    return "\n".join(lines)


def main(argv):
    check = "--check" in argv
    outputs = {QUICKREF: build_quickref(), SECTION_INDEX: build_section_index()}
    stale = []
    for path, content in outputs.items():
        current = open(path, encoding="utf-8").read() if os.path.isfile(path) else None
        if check:
            if current != content:
                stale.append(os.path.relpath(path, ROOT).replace("\\", "/"))
        else:
            os.makedirs(os.path.dirname(path), exist_ok=True)
            with open(path, "w", encoding="utf-8", newline="\n") as handle:
                handle.write(content)
            print(f"wrote {os.path.relpath(path, ROOT)} ({len(content)} bytes)")
    if check:
        if stale:
            print("STALE generated index (run `python tests/gen_spec_index.py`): " + ", ".join(stale))
            return 1
        print("generated indexes are fresh")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
