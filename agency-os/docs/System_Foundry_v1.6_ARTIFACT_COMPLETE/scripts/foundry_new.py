#!/usr/bin/env python3
from pathlib import Path
import argparse, json, hashlib, datetime, re
ROOT=Path(__file__).resolve().parents[1]
VERSION='1.6.0'
def load(rel): return json.loads((ROOT/rel).read_text())
def safe_name(s):
    x=re.sub(r'[^A-Za-z0-9._-]+','-',s).strip('-')
    if not x or x in {'.','..'}: raise ValueError('invalid project name')
    return x

def main(argv=None):
    ap=argparse.ArgumentParser(); ap.add_argument('name'); ap.add_argument('--out',required=True); ap.add_argument('--profile',default='standard',choices=['lite','standard','commercial','enterprise']); ap.add_argument('--archetype',default='web_application')
    a=ap.parse_args(argv); name=safe_name(a.name); out=Path(a.out).resolve()/name
    if out.exists(): raise SystemExit('target already exists: '+str(out))
    kr=load('registries/kernel.yaml'); now=datetime.datetime.now(datetime.timezone.utc).replace(microsecond=0).isoformat().replace('+00:00','Z')
    dirs=['src','tests/unit','tests/integration','tests/contract','tests/e2e','infra','docs','.foundry/handoffs','.foundry/verification','.foundry/migration-history']
    for d in dirs: (out/d).mkdir(parents=True,exist_ok=True)
    (out/'README.md').write_text(f'# {name}\n\nGenerated by System Foundry {VERSION}.\n',encoding='utf-8')
    lock={'foundry_version':VERSION,'kernel_digest':kr['kernel_digest'],'profile':a.profile,'archetypes':[a.archetype]}
    (out/'.foundry/foundry-lock.json').write_text(json.dumps(lock,indent=2)+'\n')
    cp={'schema_id':'control-plane','schema_version':'1.0.0','foundry_kernel_version':VERSION,'revision':1,'created_at':now,'updated_at':now}
    (out/'.foundry/control-plane-version.json').write_text(json.dumps(cp,indent=2)+'\n')
    artifacts=['project-profile.json','source-of-truth-map.json','risk-classification.json','authority-policy.json','evidence-register.json','decision-register.json','exception-register.json','lifecycle-register.json','release-register.json']
    idx={'foundry_kernel_version':VERSION,'artifacts':{x:{'schema_id':x.replace('.json',''),'schema_version':'1.0.0','revision':1,'created_at':now,'updated_at':now} for x in artifacts}}
    (out/'.foundry/artifact-index.json').write_text(json.dumps(idx,indent=2)+'\n')
    profile={'project_id':name,'profile':a.profile,'system_type':a.archetype,'criticality':'low','commercial':a.profile in ['commercial','enterprise'],'multi_tenant':False,'regulated':False}
    (out/'.foundry/project-profile.json').write_text(json.dumps(profile,indent=2)+'\n')
    for f,empty in [('source-of-truth-map.json',{'domains':[]}),('risk-classification.json',{}),('authority-policy.json',{}),('evidence-register.json',[]),('decision-register.json',[]),('exception-register.json',[]),('lifecycle-register.json',[]),('release-register.json',[])]:
        (out/'.foundry'/f).write_text(json.dumps(empty,indent=2)+'\n')
    print(out)
    return 0
if __name__=='__main__': raise SystemExit(main())
