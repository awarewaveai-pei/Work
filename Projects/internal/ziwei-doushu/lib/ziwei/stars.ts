/** 流耀前綴(運=大限、流=流年、月日時=流月流日流時)與其對應的本命星。 */
const FLOW_PREFIX: Record<string, string> = { 運: '大限', 流: '流年', 月: '流月', 日: '流日', 時: '流時' };
const FLOW_BASE: Record<string, string> = {
  祿: '祿存', 馬: '天馬', 昌: '文昌', 曲: '文曲', 羊: '擎羊',
  陀: '陀羅', 魁: '天魁', 鉞: '天鉞', 鸞: '紅鸞', 喜: '天喜',
};

/** 流耀(運祿、流羊…)對應的運限層與本命星;非流耀回 null。 */
export function flowCounterpart(name: string): { scope: string; base: string } | null {
  if (name.length !== 2) return null;
  const scope = FLOW_PREFIX[name[0]];
  const base = FLOW_BASE[name[1]];
  return scope && base ? { scope, base } : null;
}

/** 任一星的一句要點:主星取知識庫原型與長處,其餘查 STAR_NOTES,流耀指向本命星;查無回 null。 */
export function starBrief(name: string): string | null {
  const p = STAR_PROFILES[name];
  if (p) return `${p.archetype},${p.qi};長於${p.pros.slice(0, 3).join('、')}`;
  const note = STAR_NOTES[name];
  if (note) return note.note;
  const f = flowCounterpart(name);
  if (f) {
    const base = STAR_NOTES[f.base]?.note;
    return base ? `${f.scope}${f.base}:${base}` : null;
  }
  return null;
}
