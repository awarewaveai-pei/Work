def generate_forced_connections_session(
    record_id: str,
    concept_a_name: str,
    concept_a_features: list[dict[str, Any]],
    concept_b_name: str,
    concept_b_features: list[dict[str, Any]],
    combinations: list[dict[str, Any]],
    provenance: dict[str, Any],
    *,
    version: str = "1.0.0",
    generated_by_method: str = METHOD_ID,
) -> dict[str, Any]:
    """Instance of ``typed-objects/forced-connections-session.schema.yaml``.

    Enforces BOTH real invariants fail-closed, in this order: id/version/provenance/name shape, invariant #1
    (both feature pools present, well-shaped, non-empty -- computed from each pool's own raw entries BEFORE any
    combination is even looked at), combination per-field shape, THEN invariant #2 (two-sided referential
    integrity -- walks both pools' own real ids fresh, never trusts that invariant #1's own pass already proved
    anything about combinations). A dangling or wrong-pool reference is refused at construction time, never
    silently stored.
    """
    if not _is_nonempty_str(record_id) or not record_id.startswith(RECORD_ID_PREFIX):
        raise InvariantViolation(f"FORCEDCONN_INVALID_ID: record_id must be a non-empty string beginning with {RECORD_ID_PREFIX!r}, got {record_id!r}")
    if not isinstance(version, str):
        raise InvariantViolation(f"FORCEDCONN_INVALID_VERSION: version must be a string, got {version!r}")
    if not provenance_is_valid(provenance):
        raise InvariantViolation(f"FORCEDCONN_INVALID_PROVENANCE: provenance failed schema validation, got {_shallow_describe(provenance)}")
    if not _is_nonempty_str(concept_a_name):
        raise InvariantViolation(f"FORCEDCONN_EMPTY_CONCEPT_A_NAME: concept_a_name must be a non-empty string, got {concept_a_name!r}")
    if not _is_nonempty_str(concept_b_name):
        raise InvariantViolation(f"FORCEDCONN_EMPTY_CONCEPT_B_NAME: concept_b_name must be a non-empty string, got {concept_b_name!r}")

    if not _feature_pool_is_valid(concept_a_features):
        raise InvariantViolation(
            f"FORCEDCONN_EMPTY_FEATURE_POOL: concept_a_features must be a non-empty list of well-shaped "
            f"{{id, description}} entries (Atlas's own '列特徵' step); got {_shallow_describe(concept_a_features)}"
        )
    if not _feature_pool_is_valid(concept_b_features):
        raise InvariantViolation(
            f"FORCEDCONN_EMPTY_FEATURE_POOL: concept_b_features must be a non-empty list of well-shaped "
            f"{{id, description}} entries (Atlas's own '列特徵' step); got {_shallow_describe(concept_b_features)}"
        )

    if not isinstance(combinations, list) or not combinations:
        raise InvariantViolation(
            f"FORCEDCONN_EMPTY_COMBINATIONS: combinations must be a non-empty list (Atlas's own '交叉組合' step "
            f"IS the method); got {_shallow_describe(combinations)}"
        )
    if not all(_combination_entry_is_valid(entry) for entry in combinations):
        raise InvariantViolation(
            f"FORCEDCONN_INVALID_COMBINATION: every combinations[] entry must have exactly the keys "
            f"{sorted(_COMBINATION_KEYS)}, non-empty id/feature_a_ref/feature_b_ref/resulting_idea; "
            f"got {_shallow_describe(combinations)}"
        )

    valid_a_ids = set(feature_ids(concept_a_features))
    valid_b_ids = set(feature_ids(concept_b_features))
    dangling = _dangling_feature_refs(combinations, valid_a_ids, valid_b_ids)
    if dangling:
        raise InvariantViolation(
            f"FORCEDCONN_DANGLING_FEATURE_REF: {dangling} reference(s) a feature id not present in the correct "
            f"concept's own feature pool"
        )

    return {
        "id": record_id,
        "version": version,
        "generated_by_method": generated_by_method,
        "concept_a_name": concept_a_name,
        "concept_a_features": [_rebuild_feature(entry) for entry in concept_a_features],
        "concept_b_name": concept_b_name,
        "concept_b_features": [_rebuild_feature(entry) for entry in concept_b_features],
        "combinations": [_rebuild_combination(entry) for entry in combinations],
        "provenance": provenance,
    }


# --------------------------------------------------------------------------
# Gates -- independently re-derive both invariants from raw fields, fail-closed on malformed input. Never call
# generate_forced_connections_session -- a hand-tampered record that bypassed the builder entirely must be
# caught exactly as a builder-refused one would have been.
# --------------------------------------------------------------------------


def _result(gate_id: str, passed: bool, evidence: list[Any], validator: str, timestamp: str) -> dict[str, Any]:
    return {"gate_id": gate_id, "status": "PASS" if passed else "FAIL", "evidence": evidence, "validator": validator, "timestamp": timestamp}


def evaluate_provenance_required_gate(record: dict[str, Any], validator: str, timestamp: str) -> dict[str, Any]:
    """Contract ``quality.provenance_required: true`` -- the record's own top-level provenance is schema-valid.
    Fails closed on non-dict input."""
    if not isinstance(record, dict):
        return _result("provenance_required", False, [{"reason": "record is not a dict"}], validator, timestamp)
    passed = provenance_is_valid(record.get("provenance"))
    return _result("provenance_required", passed, [{"provenance_valid": passed}], validator, timestamp)


def evaluate_feature_pools_gate(record: dict[str, Any], validator: str, timestamp: str) -> dict[str, Any]:
    """Invariant #1, re-derived independently and fully: re-checks ``id``/``version``/``concept_a_name``/
    ``concept_b_name`` plus a full ``_feature_pool_is_valid`` pass over the record's own stored
    ``concept_a_features``/``concept_b_features``. Does NOT call ``generate_forced_connections_session`` and does
    not trust any stored flag. FAILS CLOSED on malformed input rather than crashing."""
    if not isinstance(record, dict):
        return _result("feature_pools", False, [{"reason": "record is not a dict"}], validator, timestamp)
    if not _is_nonempty_str(record.get("id")) or not record.get("id", "").startswith(RECORD_ID_PREFIX):
        return _result("feature_pools", False, [{"reason": f"id missing, empty, or not prefixed {RECORD_ID_PREFIX!r}"}], validator, timestamp)
    if not isinstance(record.get("version"), str):
        return _result("feature_pools", False, [{"reason": "version missing or not a string"}], validator, timestamp)
    if not _is_nonempty_str(record.get("concept_a_name")):
        return _result("feature_pools", False, [{"reason": "concept_a_name missing or empty"}], validator, timestamp)
    if not _is_nonempty_str(record.get("concept_b_name")):
        return _result("feature_pools", False, [{"reason": "concept_b_name missing or empty"}], validator, timestamp)

    a_ok = _feature_pool_is_valid(record.get("concept_a_features"))
    b_ok = _feature_pool_is_valid(record.get("concept_b_features"))
    passed = a_ok and b_ok
    return _result(
        "feature_pools",
        passed,
        [{"concept_a_features_valid": a_ok, "concept_b_features_valid": b_ok}],
        validator,
        timestamp,
    )


def evaluate_combination_referential_integrity_gate(record: dict[str, Any], validator: str, timestamp: str) -> dict[str, Any]:
    """Invariant #2, THE real differentiator, re-derived independently: re-collects both pools' own real ids
    fresh from the record's OWN raw fields (never trusts that ``evaluate_feature_pools_gate`` already ran, or
    that the builder ever ran at all), then checks every ``combinations[]`` entry's own ``feature_a_ref``/
    ``feature_b_ref`` against the CORRECT side's set. Also re-derives ``combinations`` non-emptiness (Atlas's own
    method IS the cross-combination step). FAILS CLOSED on malformed input rather than crashing."""
    if not isinstance(record, dict):
        return _result("combination_referential_integrity", False, [{"reason": "record is not a dict"}], validator, timestamp)

    concept_a_features = record.get("concept_a_features")
    concept_b_features = record.get("concept_b_features")
    if not _feature_pool_is_valid(concept_a_features) or not _feature_pool_is_valid(concept_b_features):
        return _result(
            "combination_referential_integrity",
            False,
            [{"reason": "concept_a_features or concept_b_features invalid -- cannot evaluate combination references"}],
            validator,
            timestamp,
        )

    combinations = record.get("combinations")
    if not isinstance(combinations, list) or not combinations:
        return _result("combination_referential_integrity", False, [{"reason": "combinations missing, not a list, or empty"}], validator, timestamp)
    if not all(_combination_entry_is_valid(entry) for entry in combinations):
        return _result("combination_referential_integrity", False, [{"reason": "combinations contains a malformed entry"}], validator, timestamp)

    valid_a_ids = set(feature_ids(concept_a_features))
    valid_b_ids = set(feature_ids(concept_b_features))
    dangling = _dangling_feature_refs(combinations, valid_a_ids, valid_b_ids)
    return _result(
        "combination_referential_integrity",
        not dangling,
        [{"dangling_combinations": dangling, "combination_count": len(combinations)}],
        validator,
        timestamp,
    )


def evaluate_forced_connections_gates(record: dict[str, Any], validator: str, timestamp: str) -> list[dict[str, Any]]:
    """All 3 of the contract's real gates, in catalog order: the one declared ``quality`` property, then both
    independent structural-integrity re-derivations. No ``evidence_labeling_required`` gate -- the contract sets
    that flag to ``false``, same "only emit gates for what is actually declared true" discipline every sibling
    module in this suite already establishes."""
    return [
        evaluate_provenance_required_gate(record, validator, timestamp),
        evaluate_feature_pools_gate(record, validator, timestamp),
        evaluate_combination_referential_integrity_gate(record, validator, timestamp),
    ]


def all_gates_pass(gate_results: list[dict[str, Any]]) -> bool:
    return all(gate["status"] in {"PASS", "NOT_APPLICABLE"} for gate in gate_results)
