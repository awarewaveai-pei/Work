from __future__ import annotations

from typing import Any

from ai_lego.core.domain.provenance import provenance_is_valid
from ai_lego.errors import InvariantViolation

METHOD_ID = "divergent.forced_connections"
RECORD_ID_PREFIX = "FORCEDCONN-"

_FEATURE_KEYS = frozenset({"id", "description"})
_COMBINATION_KEYS = frozenset({"id", "feature_a_ref", "feature_b_ref", "resulting_idea"})


def _is_nonempty_str(value: Any) -> bool:
    return isinstance(value, str) and bool(value.strip())


def _shallow_describe(value: Any) -> str:
    """One-level-deep description for error messages -- NEVER Python's own recursive ``repr()``, same
    discipline every prior module in this codebase (``functional_decomposition``/``attack_tree``/``fault_tree``)
    already establishes."""
    if isinstance(value, list):
        return f"<list of {len(value)} item(s)>"
    if isinstance(value, dict):
        return f"<dict with keys {sorted(map(str, value.keys()))}>"
    return repr(value)


def _feature_entry_is_valid(entry: Any) -> bool:
    if not isinstance(entry, dict) or set(entry.keys()) != _FEATURE_KEYS:
        return False
    return _is_nonempty_str(entry.get("id")) and _is_nonempty_str(entry.get("description"))


def _feature_pool_is_valid(pool: Any) -> bool:
    """Invariant #1's own shape+non-emptiness check, shared by builder and gate. Non-empty per the method
    contract's own preconditions (Atlas's own '列特徵' step, presumed done for both sides)."""
    return isinstance(pool, list) and bool(pool) and all(_feature_entry_is_valid(entry) for entry in pool)


def _combination_entry_is_valid(entry: Any) -> bool:
    """Per-field shape only -- does NOT check referential integrity (invariant #2's own job, checked once both
    pools' real ids are known, see ``_dangling_feature_refs`` below)."""
    if not isinstance(entry, dict) or set(entry.keys()) != _COMBINATION_KEYS:
        return False
    return (
        _is_nonempty_str(entry.get("id"))
        and _is_nonempty_str(entry.get("feature_a_ref"))
        and _is_nonempty_str(entry.get("feature_b_ref"))
        and _is_nonempty_str(entry.get("resulting_idea"))
    )


def _rebuild_feature(entry: dict[str, Any]) -> dict[str, Any]:
    """Fresh dict, never the caller's own object -- same aliasing-fix discipline
    ``decomposition.functional_decomposition``'s own ``_rebuild_node``/``_rebuild_interface`` establish (critic
    finding, 2026-09-11, on that sibling module: without a rebuild, a caller retaining a reference to its input
    could mutate an already-validated record in place with no error and no re-validation)."""
    return {"id": entry["id"], "description": entry["description"]}


def _rebuild_combination(entry: dict[str, Any]) -> dict[str, Any]:
    return {
        "id": entry["id"],
        "feature_a_ref": entry["feature_a_ref"],
        "feature_b_ref": entry["feature_b_ref"],
        "resulting_idea": entry["resulting_idea"],
    }


def feature_ids(pool: list[dict[str, Any]]) -> list[str]:
    """Every id in one feature pool, in declared order. PURE -- no validation; callers must have already
    confirmed the pool is ``_feature_pool_is_valid``. The single shared source both invariant #1 (non-emptiness,
    trivially true once this runs) and invariant #2 (referential lookup, via the ``set()`` below) build on."""
    return [entry["id"] for entry in pool]


def _dangling_feature_refs(combinations: list[dict[str, Any]], valid_a_ids: set[str], valid_b_ids: set[str]) -> list[dict[str, Any]]:
    """Checks EACH side against its OWN pool only -- a ``feature_a_ref`` that resolves in ``concept_b_features``
    but not ``concept_a_features`` is dangling exactly the same as one that resolves nowhere (module docstring's
    own invariant #2: wrong-pool and no-pool are both refused, never distinguished as a lesser defect)."""
    dangling: list[dict[str, Any]] = []
    for entry in combinations:
        problems: list[str] = []
        if entry["feature_a_ref"] not in valid_a_ids:
            problems.append("feature_a_ref")
        if entry["feature_b_ref"] not in valid_b_ids:
            problems.append("feature_b_ref")
        if problems:
            dangling.append(
                {
                    "combination_id": entry["id"],
                    "feature_a_ref": entry["feature_a_ref"],
                    "feature_b_ref": entry["feature_b_ref"],
                    "invalid_fields": problems,
                }
            )
    return dangling


# --------------------------------------------------------------------------
# Convenience constructors -- eager, minimal validation, same discipline every prior module's own constructors
# use. NOT the invariant boundary: generate_forced_connections_session validates whatever dicts it is handed
# regardless of how they were built (a raw hand-built dict is exercised the same way in the CLI slice/tests).
# --------------------------------------------------------------------------


def feature(feature_id: str, description: str) -> dict[str, Any]:
    if not _is_nonempty_str(feature_id):
        raise InvariantViolation(f"FORCEDCONN_EMPTY_FEATURE_ID: id must be a non-empty string, got {feature_id!r}")
    if not _is_nonempty_str(description):
        raise InvariantViolation(f"FORCEDCONN_EMPTY_FEATURE_DESCRIPTION: description must be a non-empty string, got {description!r}")
    return {"id": feature_id, "description": description}


def combination(combination_id: str, feature_a_ref: str, feature_b_ref: str, resulting_idea: str) -> dict[str, Any]:
    """One INPUT entry for ``generate_forced_connections_session``'s own ``combinations`` parameter. Convenience
    constructor only -- does NOT itself check that the refs resolve to a real feature id in the correct pool
    (that requires knowing both pools, which this function is never handed); the builder performs that check
    once both pools and the combinations are all in hand."""
    if not _is_nonempty_str(combination_id):
        raise InvariantViolation(f"FORCEDCONN_EMPTY_COMBINATION_ID: id must be a non-empty string, got {combination_id!r}")
    if not _is_nonempty_str(feature_a_ref):
        raise InvariantViolation(f"FORCEDCONN_EMPTY_FEATURE_A_REF: feature_a_ref must be a non-empty string, got {feature_a_ref!r}")
    if not _is_nonempty_str(feature_b_ref):
        raise InvariantViolation(f"FORCEDCONN_EMPTY_FEATURE_B_REF: feature_b_ref must be a non-empty string, got {feature_b_ref!r}")
    if not _is_nonempty_str(resulting_idea):
        raise InvariantViolation(f"FORCEDCONN_EMPTY_RESULTING_IDEA: resulting_idea must be a non-empty string, got {resulting_idea!r}")
    return {"id": combination_id, "feature_a_ref": feature_a_ref, "feature_b_ref": feature_b_ref, "resulting_idea": resulting_idea}


