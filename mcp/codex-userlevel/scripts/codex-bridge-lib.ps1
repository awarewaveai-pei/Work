# Shared helpers for sync-claude-to-codex.ps1 and check-claude-codex-parity.ps1.
# Dot-source only. One implementation per fact, so the generator and the verifier
# can never disagree about the same input.

# A .skill package is a zip. Read it in-process: shelling out to `tar` resolves
# to Git Bash's GNU tar under the Claude hook shell, which parses `D:\...` as
# host:path and fails (froze the Codex bridge sync from 2026-09-01 to 09-19).
function Get-SkillArchiveTopFolder {
  param([Parameter(Mandatory)][string]$Path)
  Add-Type -AssemblyName System.IO.Compression.FileSystem
  $zip = [System.IO.Compression.ZipFile]::OpenRead($Path)
  try {
    $skillEntry = @($zip.Entries | Where-Object { $_.FullName -match '^[^/\\]+[/\\]SKILL\.md$' }) | Select-Object -First 1
    if (-not $skillEntry) { throw "No <folder>/SKILL.md entry in skill archive: $Path" }
    return ($skillEntry.FullName -split '[/\\]')[0]
  } finally {
    $zip.Dispose()
  }
}

# Codex user-level hook wiring, generated per machine. Commands are deliberately
# unquoted and free of $, %, & so they run identically whether Codex spawns them
# through cmd.exe, PowerShell or Git Bash (all three are reported across Codex
# versions on Windows); a WorkRoot with whitespace therefore fails loudly.
function Get-CodexUserHooksDocument {
  param([Parameter(Mandatory)][string]$WorkRoot)
  if ($WorkRoot -match '\s') {
    throw "WorkRoot '$WorkRoot' contains whitespace; Codex hook commands must stay unquoted to be shell-neutral."
  }
  $hookDir = ($WorkRoot.TrimEnd('\', '/') + '/mcp/claude-userlevel/hooks') -replace '\\', '/'
  $runner = "node $hookDir/runner.js"
  $ps = 'powershell.exe -NoProfile -WindowStyle Hidden -ExecutionPolicy Bypass -File'
  $h = { param($cmd, $timeout) [ordered]@{ type = 'command'; command = $cmd; timeout = $timeout } }
  return [ordered]@{
    description = 'GENERATED by mcp/codex-userlevel/scripts/sync-claude-to-codex.ps1 from the canonical Claude hook source. Do not edit by hand; trust via Codex /hooks after any change.'
    hooks       = [ordered]@{
      PreToolUse       = @([ordered]@{ matcher = '.*'; hooks = @((& $h "$runner PreToolUse --host=codex" 60)) })
      PostToolUse      = @(
        [ordered]@{ matcher = '.*'; hooks = @((& $h "$runner PostToolUse --host=codex" 90)) },
        [ordered]@{ matcher = '^(Bash|exec_command|shell|local_shell|unified_exec)$'; hooks = @((& $h "$ps $hookDir/post-push-trigger-deploy.ps1" 3600)) }
      )
      SessionStart     = @([ordered]@{ matcher = 'startup|resume'; hooks = @((& $h "$runner SessionStart --host=codex" 15)) })
      UserPromptSubmit = @([ordered]@{ hooks = @(
            (& $h "$ps $hookDir/ao-resume-on-prompt.ps1 -HookHost codex" 1200),
            (& $h "$runner UserPromptSubmit --host=codex" 15)
          ) })
      Stop             = @([ordered]@{ hooks = @((& $h "$runner Stop --host=codex" 300)) })
      SubagentStart    = @([ordered]@{ hooks = @((& $h "$runner SubagentStart --host=codex" 15)) })
    }
  }
}

function Get-CodexUserHooksJson {
  param([Parameter(Mandatory)][string]$WorkRoot)
  return ((Get-CodexUserHooksDocument -WorkRoot $WorkRoot) | ConvertTo-Json -Depth 10)
}

# Claude memory index for a repo: ~/.claude/projects/<root with : \ / replaced by -> /memory/MEMORY.md
# Keep this file ASCII-only: Windows PowerShell 5.1 reads BOM-less .ps1 as CP950.
function Get-ClaudeMemoryIndexPath {
  param([Parameter(Mandatory)][string]$WorkRoot)
  $slug = $WorkRoot.TrimEnd('\', '/') -replace '[^A-Za-z0-9]', '-'
  return (Join-Path $env:USERPROFILE (Join-Path '.claude\projects' (Join-Path $slug 'memory\MEMORY.md')))
}
