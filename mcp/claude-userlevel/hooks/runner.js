#!/usr/bin/env node
// Hook runner — single entry point for all portable governance hooks.
//
//   node runner.js <event>
//   event ∈ PreToolUse | PostToolUse | PostToolUseFailure | Stop | SessionStart |
//           UserPromptSubmit | SubagentStart
//
// Replaces 23 standalone hook files that each hand-rolled the same lifecycle
// (stdin read → JSON parse → try/catch → fail-open → exit). The lifecycle now
// lives HERE, exactly once; the judgment logic lives in rules/ as plain
// modules with a check(ctx) function and no process handling at all.
//
// Guarantees (structural, not per-rule discipline):
//   - FAIL-OPEN: a rule that crashes, or a rule file that is missing/broken,
//     never blocks the tool call. The failure is written loudly to stderr AND
//     to the persistent fail-open log (lib/shared.logFailOpen).
//   - ISOLATION: each rule is loaded and executed inside its own try/catch —
//     one broken rule cannot take down the others.
//   - ONE SID, ONE FLAG SCHEME, ONE LOG: rules consume ctx.sid / ctx.flags /
//     ctx.shared; they never derive their own.
//   - BLOCK AGGREGATION: every matching rule runs; all block messages are
//     printed together, then exit 2 (Claude Code treats exit 2 as BLOCK and
//     forwards stderr; any other exit is non-blocking).
//
// Wiring (thin, three consumers, one manifest):
//   settings.template.json  → node ~/.claude/hooks/runner.js <event>
//   hooks.json (plugin)     → node ${CLAUDE_PLUGIN_ROOT}/hooks/runner.js <event>
//   .claude/settings.local.json (remote containers, generated by
//     scripts/wire-remote-hooks.sh) → node "$CLAUDE_PROJECT_DIR/mcp/claude-userlevel/hooks/runner.js" <event>
//   ~/.codex/hooks.json (generated by mcp/codex-userlevel/scripts/sync-claude-to-codex.ps1)
//     → node <abs>/runner.js <event> --host=codex ; payload translated by lib/codex-adapter.js
//
// The event→rules map is rules.manifest.json (SSOT — no hand-written counts
// anywhere; the SessionStart banner derives its numbers from the manifest).
//
// Test override: CLAUDE_HOOKS_RUNNER_HOME points the runner at an alternate
// directory containing rules.manifest.json + rules/ (used by tests/hooks/).

const fs = require('fs');
const path = require('path');

const HOME_DIR = process.env.CLAUDE_HOOKS_RUNNER_HOME || __dirname;
const MANIFEST_PATH = path.join(HOME_DIR, 'rules.manifest.json');

// shared lib is loaded defensively: if it is broken/missing we still fail-open
// (passthrough) instead of crashing before any logging is possible.
let shared = null;
try { shared = require('./lib/shared'); } catch (_) { /* degraded mode below */ }
let codexAdapter = null;
try { codexAdapter = require('./lib/codex-adapter'); } catch (_) { /* Codex payloads then reach rules untranslated */ }
let codexHeartbeat = null;
try { codexHeartbeat = require('./lib/codex-heartbeat'); } catch (_) { /* no proof-of-execution record */ }

function failOpenLog(name, err) {
  try {
    if (shared) { shared.logFailOpen(name, err); return; }
  } catch (_) { /* fall through */ }
  // Degraded mode: shared lib itself unavailable — stderr is all we have.
  process.stderr.write(`[Hook][fail-open] ${name}: ${(err && err.message) || err}\n`);
}

// Unwrap `bash -c "…"` / `sh -lc '…'` payload strings (depth-limited) so
// command-scanning rules can match verbs hidden inside a shell wrapper.
// Appended as extra lines, so ^-anchored multiline patterns keep working.
const SHELL_C_RE = /\b(?:bash|sh|zsh|dash)\s+(?:-[A-Za-z-]+\s+)*-[A-Za-z]*c\s+(?:"([^"]+)"|'([^']+)')/g;
// Same for the Windows wrappers. Codex on Windows dispatches every shell call as
// `"C:\...\powershell.exe" -Command '<real command>'`, so without this every
// command-position rule (--no-verify, deny mirror, high-risk ssh, ...) sees only
// the wrapper and matches nothing -- found by a live Codex probe on 2026-09-20.
const WIN_C_RE = /(?:powershell(?:\.exe)?|pwsh(?:\.exe)?)["']?\s+(?:-[A-Za-z]+(?:\s+\S+)?\s+)*-(?:c|Command)\s+(?:"((?:[^"\\]|\\.)+)"|'((?:[^'])+)')|(?:\bcmd(?:\.exe)?["']?\s+(?:\/[a-zA-Z]\s+)*\/[cCkK]\s+(?:"([^"]+)"|'([^']+)'|(\S.*)))/g;
function expandCommand(cmd) {
  const seen = [String(cmd || '')];
  let frontier = seen.slice();
  for (let depth = 0; depth < 3 && frontier.length; depth++) {
    const next = [];
    for (const text of frontier) {
      for (const re of [SHELL_C_RE, WIN_C_RE]) {
        re.lastIndex = 0;
        for (const m of text.matchAll(re)) {
          const payload = m.slice(1).find((g) => g);
          if (payload) next.push(payload.replace(/\\"/g, '"'));
        }
      }
    }
    seen.push(...next);
    frontier = next;
  }
  return seen.join('\n');
}

// Split expanded command text into COMMAND-POSITION segments: the start of
// every line plus the token after each shell chain operator (&& || ; |).
// Rules that must distinguish "invoking rm -rf" from "prose that mentions
// rm -rf" anchor ^ against these segments instead of the full text.
// (Two live false-positives on 2026-07-02 — a docs heredoc tripped the
// dangerous-bash and verify-gate-commit gates — created this helper.)
// Deliberately NOT split on backticks/$() — markdown-heavy commands would
// turn every inline code span into a fake command position.
function commandSegments(expanded) {
  const segs = [];
  for (const line of String(expanded).split('\n')) {
    for (const part of line.split(/&&|\|\||;|\|/)) {
      const t = part.trim();
      if (t) segs.push(t);
    }
  }
  return segs;
}

function collectFiles(toolInput) {
  const files = [];
  const add = (f) => { if (f && !files.includes(f)) files.push(f); };
  if (toolInput) add(toolInput.file_path);
  if (toolInput && Array.isArray(toolInput.edits)) {
    for (const e of toolInput.edits) if (e) add(e.file_path);
  }
  return files;
}

function loadManifest() {
  return JSON.parse(fs.readFileSync(MANIFEST_PATH, 'utf8'));
}

function matcherHits(matcher, toolName) {
  if (matcher == null || matcher === '' ) return true; // omitted → match all
  try {
    return new RegExp(matcher).test(toolName);
  } catch (e) {
    failOpenLog(`runner matcher(${matcher})`, e);
    return false; // broken matcher never fires (and never blocks)
  }
}

function main() {
  const event = process.argv[2] || '';
  let d = '';
  // utf8 decoding on the stream (critic finding 6): without setEncoding, a
  // multibyte character split across chunk boundaries decodes to U+FFFD twice
  // — corrupts CJK command text in audit logs and future content matching.
  process.stdin.setEncoding('utf8');
  process.stdin.on('data', (c) => { d += c; });
  process.stdin.on('end', () => {
    let blocks = [];
    const contexts = [];
    let isCodexPayload = false;
    // These events add stdout to model/developer context. Rules return
    // { context: [lines] }; raw stdin must never be echoed or it would inject
    // the event payload into the conversation. SubagentStart makes the shared
    // engineering charter mechanically inherited by every spawned agent.
    const isContextEvent = event === 'UserPromptSubmit' || event === 'SubagentStart';
    // Per the official Claude Code hooks reference (checked 2026-09-03): only
    // a short whitelist of events treat plain stdout as injected context --
    // UserPromptSubmit is one of them. Every OTHER context event (currently
    // just SubagentStart) is NOT on that list and requires the structured
    // hookSpecificOutput.additionalContext JSON shape; plain stdout is
    // silently dropped there, exactly like Codex's contract. Root cause of a
    // real bug: this rule used to only branch on isCodexPayload, so native
    // Claude SubagentStart wrote plain text that the host never surfaced --
    // no crash, no fail-open entry, charter simply never reached the
    // subagent. Extend this set if a future event needs the same treatment.
    const PLAIN_STDOUT_CONTEXT_EVENTS = new Set(['UserPromptSubmit']);
    // PreToolUse is NOT a pure context event like the two above (a
    // non-blocking call with no rule context must still pass through
    // untouched — see the final fallback branch below), but per the
    // official docs it DOES honor hookSpecificOutput.additionalContext when
    // a rule returns one, alongside permissionDecision:"allow" (2026-09-03).
    // CONFIRMED by a real Agent-tool spawn (2026-09-03, this host = Claude
    // Desktop app): additionalContext returned from a PreToolUse ^Agent$
    // rule is delivered into the freshly-spawned SUBAGENT's own context
    // (the spawned agent quoted it back verbatim, unprompted) -- not just
    // surfaced to the calling parent. This is the mechanism subagent-charter
    // now rides on instead of SubagentStart (see rules.manifest.json), which
    // real spawn testing separately proved never reaches this host at all.
    // NOTE: unlike `updatedInput` (confirmed via two independent, closed
    // Claude Code GitHub issues to be silently ignored for the Agent tool's
    // own prompt field), additionalContext is NOT silently dropped here --
    // don't conflate the two fields' reliability.
    const isPreToolUseContext = event === 'PreToolUse';
    try {
      let payload;
      try { payload = JSON.parse(d); } catch (_) { payload = null; }
      // `hook_event_name` is NOT a valid Codex signal -- confirmed against both
      // vendors' official hook docs (2026-09-03): Claude Code's own PreToolUse/
      // PostToolUse payload includes `hook_event_name` as a standard field
      // (code.claude.com/docs/en/hooks), so the old check classified every real
      // Claude Code call as Codex. `turn_id` (and `model`) are documented
      // Codex-specific extensions, absent from Claude Code's schema
      // (learn.chatgpt.com/docs/hooks: "Turn-scoped hooks list turn_id as a
      // Codex-specific extension") -- use that instead.
      // `--host=codex` is set by the generated ~/.codex/hooks.json wiring and is
      // the authoritative signal: Codex documents turn_id only on tool events,
      // so SessionStart/UserPromptSubmit/Stop would otherwise read as Claude.
      const isCodexHost = process.argv.slice(3).includes('--host=codex');
      isCodexPayload = isCodexHost || !!(payload && typeof payload === 'object' && typeof payload.turn_id === 'string');
      if (isCodexHost && codexHeartbeat) {
        try { codexHeartbeat.record(event, payload && typeof payload === 'object' ? payload : null); }
        catch (e) { failOpenLog('runner codex heartbeat', e); }
      }
      if (payload === null || typeof payload !== 'object') {
        // Claude Code expects its original stdin echoed on ordinary pass-through
        // events. Codex command hooks ignore plain stdout, so never echo an
        // unparseable Codex payload back into its event stream.
        if (!isContextEvent && !isCodexPayload) process.stdout.write(d);
        return; // unparseable stdin → passthrough (fail-open)
      }

      const rawPayload = payload;
      let ruleEvent = event;
      if (isCodexPayload && codexAdapter) {
        try {
          const translated = codexAdapter.toCanonical(event, payload);
          ruleEvent = translated.event;
          payload = translated.payload;
        } catch (e) { failOpenLog('runner codex adapter', e); }
      }

      const manifest = loadManifest();
      const groups = (manifest.events && manifest.events[ruleEvent]) || [];
      const toolName = String(payload.tool_name || '');
      const toolInput = (payload.tool_input && typeof payload.tool_input === 'object')
        ? payload.tool_input : {};
      const command = String(toolInput.command || '');

      const expanded = expandCommand(command);
      const ctx = {
        event: ruleEvent,
        payload,
        rawPayload,
        host: isCodexPayload ? 'codex' : 'claude',
        toolName,
        toolInput,
        command,
        commandExpanded: expanded,
        commandSegments: commandSegments(expanded),
        files: collectFiles(toolInput),
        sid: shared ? shared.getSessionId(payload) : 'no-shared-lib',
        cwd: process.cwd(),
        shared,
        flags: null, // set below (lazy require, defensive)
        manifest,
        argRest: process.argv.slice(3),
      };
      try { ctx.flags = require('./lib/flags'); } catch (e) { failOpenLog('runner flags lib', e); }

      for (const group of groups) {
        if (!matcherHits(group.matcher, toolName)) continue;
        for (const ruleName of group.rules || []) {
          let mod;
          try {
            mod = require(path.join(HOME_DIR, 'rules', ruleName + '.js'));
          } catch (e) {
            failOpenLog(`rule load ${ruleName}`, e);
            process.stderr.write(`[Hook][fail-open] rule '${ruleName}' failed to load — gate inactive, see fail-open log.\n`);
            continue;
          }
          try {
            const res = mod.check(ctx);
            if (res && Array.isArray(res.warn)) {
              for (const ln of res.warn) process.stderr.write(ln + '\n');
            }
            if (res && Array.isArray(res.context)) {
              contexts.push(...res.context);
            }
            if (res && Array.isArray(res.block) && res.block.length) {
              blocks.push(...res.block);
            }
          } catch (e) {
            failOpenLog(`rule ${ruleName}`, e);
            process.stderr.write(`[Hook][fail-open] rule '${ruleName}' crashed — gate inactive for this call, see fail-open log.\n`);
          }
        }
      }
    } catch (e) {
      failOpenLog('runner', e);
      blocks = []; // runner-level failure NEVER blocks
    }

    if (blocks.length) {
      for (const ln of blocks) process.stderr.write(ln + '\n');
      if (isCodexPayload) {
        // Codex ignores exit 2 here (live probe, CLI 0.155.1: a blocked
        // `git commit --no-verify` still ran). Its documented channel is a JSON
        // decision on stdout, so emit that and exit 0 -- a non-zero exit would
        // make Codex treat the hook itself as failed and drop the decision.
        const reason = blocks.join('\n');
        const decision = event === 'PreToolUse'
          ? { hookSpecificOutput: { hookEventName: 'PreToolUse', permissionDecision: 'deny', permissionDecisionReason: reason } }
          : { decision: 'block', reason };
        process.stdout.write(JSON.stringify(decision), () => process.exit(0));
        return;
      }
      // flush-guarded exit(2) — required on Windows pipes
      process.stderr.write('', () => process.exit(2));
      return;
    }
    if (isContextEvent) {
      // Claude accepts plain context text only for events on the whitelist
      // above. Codex always requires the documented JSON hook output shape;
      // so does every other native-Claude context event. Never emit raw stdin.
      const needsStructuredContext = isCodexPayload || !PLAIN_STDOUT_CONTEXT_EVENTS.has(event);
      if (needsStructuredContext && contexts.length) {
        process.stdout.write(JSON.stringify({
          hookSpecificOutput: {
            hookEventName: event,
            additionalContext: contexts.join('\n'),
          },
        }));
      } else {
        for (const ln of contexts) process.stdout.write(ln + '\n');
      }
      return;
    }
    // Codex does not document additionalContext on PreToolUse; its SubagentStart
    // event carries the charter instead, so Codex falls through to the stderr path.
    if (isPreToolUseContext && contexts.length && !isCodexPayload) {
      // Structured JSON per the official contract — see the const above for
      // why this differs from the plain-stderr-warn degrade path below.
      // permissionDecision:"allow" is explicit: blocks already returned
      // earlier via exit 2, so reaching here always means "let it proceed."
      process.stdout.write(JSON.stringify({
        hookSpecificOutput: {
          hookEventName: 'PreToolUse',
          permissionDecision: 'allow',
          additionalContext: contexts.join('\n'),
        },
      }));
      return;
    }
    if (contexts.length) {
      // context on non-prompt events degrades to a stderr warn (visible, not injected)
      for (const ln of contexts) process.stderr.write(ln + '\n');
    }
    if (!isCodexPayload) process.stdout.write(d);
  });
}

main();
