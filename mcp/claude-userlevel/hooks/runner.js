#!/usr/bin/env node
// Hook runner — single entry point for all portable governance hooks.
//
//   node runner.js <event>
//   event ∈ PreToolUse | PostToolUse | PostToolUseFailure | Stop | SessionStart | UserPromptSubmit
//
// Replaces 23 standalone hook files that each hand-rolled the same lifecycle
// (stdin read → JSON parse → try/catch → fail-open → exit). The lifecycle now
// lives HERE, exactly once; the judgment logic lives in rules/ as plain
// modules with a check(ctx) function and no process handling at all.
//
// Guarantees (structural, not per-rule discipline):
//   - FAIL-OPEN: a rule that crashes, or a rule file that is missing/broken,
//     never blocks the tool call. The failure is written loudly to stderr AND
//     to the persistent fail-open log (lib/shared.logFailOpen).
//   - ISOLATION: each rule is loaded and executed inside its own try/catch —
//     one broken rule cannot take down the others.
//   - ONE SID, ONE FLAG SCHEME, ONE LOG: rules consume ctx.sid / ctx.flags /
//     ctx.shared; they never derive their own.
//   - BLOCK AGGREGATION: every matching rule runs; all block messages are
//     printed together, then exit 2 (Claude Code treats exit 2 as BLOCK and
//     forwards stderr; any other exit is non-blocking).
//
// Wiring (thin, three consumers, one manifest):
//   settings.template.json  → node ~/.claude/hooks/runner.js <event>
//   hooks.json (plugin)     → node ${CLAUDE_PLUGIN_ROOT}/hooks/runner.js <event>
//   .claude/settings.local.json (remote containers, generated by
//     scripts/wire-remote-hooks.sh) → node "$CLAUDE_PROJECT_DIR/mcp/claude-userlevel/hooks/runner.js" <event>
//
// The event→rules map is rules.manifest.json (SSOT — no hand-written counts
// anywhere; the SessionStart banner derives its numbers from the manifest).
//
// Test override: CLAUDE_HOOKS_RUNNER_HOME points the runner at an alternate
// directory containing rules.manifest.json + rules/ (used by tests/hooks/).

const fs = require('fs');
const path = require('path');

const HOME_DIR = process.env.CLAUDE_HOOKS_RUNNER_HOME || __dirname;
const MANIFEST_PATH = path.join(HOME_DIR, 'rules.manifest.json');

// shared lib is loaded defensively: if it is broken/missing we still fail-open
// (passthrough) instead of crashing before any logging is possible.
let shared = null;
try { shared = require('./lib/shared'); } catch (_) { /* degraded mode below */ }

function failOpenLog(name, err) {
  try {
    if (shared) { shared.logFailOpen(name, err); return; }
  } catch (_) { /* fall through */ }
  // Degraded mode: shared lib itself unavailable — stderr is all we have.
  process.stderr.write(`[Hook][fail-open] ${name}: ${(err && err.message) || err}\n`);
}

// Unwrap `bash -c "…"` / `sh -lc '…'` payload strings (depth-limited) so
// command-scanning rules can match verbs hidden inside a shell wrapper.
// Appended as extra lines, so ^-anchored multiline patterns keep working.
const SHELL_C_RE = /\b(?:bash|sh|zsh|dash)\s+(?:-[A-Za-z-]+\s+)*-[A-Za-z]*c\s+(?:"([^"]+)"|'([^']+)')/g;
function expandCommand(cmd) {
  const seen = [String(cmd || '')];
  let frontier = seen.slice();
  for (let depth = 0; depth < 3 && frontier.length; depth++) {
    const next = [];
    for (const text of frontier) {
      for (const m of text.matchAll(SHELL_C_RE)) {
        const payload = m[1] || m[2];
        if (payload) next.push(payload);
      }
    }
    seen.push(...next);
    frontier = next;
  }
  return seen.join('\n');
}

// Split expanded command text into COMMAND-POSITION segments: the start of
// every line plus the token after each shell chain operator (&& || ; |).
// Rules that must distinguish "invoking rm -rf" from "prose that mentions
// rm -rf" anchor ^ against these segments instead of the full text.
// (Two live false-positives on 2026-07-02 — a docs heredoc tripped the
// dangerous-bash and verify-gate-commit gates — created this helper.)
// Deliberately NOT split on backticks/$() — markdown-heavy commands would
// turn every inline code span into a fake command position.
function commandSegments(expanded) {
  const segs = [];
  for (const line of String(expanded).split('\n')) {
    for (const part of line.split(/&&|\|\||;|\|/)) {
      const t = part.trim();
      if (t) segs.push(t);
    }
  }
  return segs;
}

function collectFiles(toolInput) {
  const files = [];
  if (toolInput && toolInput.file_path) files.push(toolInput.file_path);
  if (toolInput && Array.isArray(toolInput.edits)) {
    for (const e of toolInput.edits) if (e && e.file_path) files.push(e.file_path);
  }
  return files;
}

function loadManifest() {
  return JSON.parse(fs.readFileSync(MANIFEST_PATH, 'utf8'));
}

function matcherHits(matcher, toolName) {
  if (matcher == null || matcher === '' ) return true; // omitted → match all
  try {
    return new RegExp(matcher).test(toolName);
  } catch (e) {
    failOpenLog(`runner matcher(${matcher})`, e);
    return false; // broken matcher never fires (and never blocks)
  }
}

function main() {
  const event = process.argv[2] || '';
  let d = '';
  process.stdin.on('data', (c) => { d += c; });
  process.stdin.on('end', () => {
    let blocks = [];
    try {
      let payload;
      try { payload = JSON.parse(d); } catch (_) { payload = null; }
      if (payload === null || typeof payload !== 'object') {
        process.stdout.write(d);
        return; // unparseable stdin → passthrough (fail-open)
      }

      const manifest = loadManifest();
      const groups = (manifest.events && manifest.events[event]) || [];
      const toolName = String(payload.tool_name || '');
      const toolInput = (payload.tool_input && typeof payload.tool_input === 'object')
        ? payload.tool_input : {};
      const command = String(toolInput.command || '');

      const expanded = expandCommand(command);
      const ctx = {
        event,
        payload,
        toolName,
        toolInput,
        command,
        commandExpanded: expanded,
        commandSegments: commandSegments(expanded),
        files: collectFiles(toolInput),
        sid: shared ? shared.getSessionId(payload) : 'no-shared-lib',
        cwd: process.cwd(),
        shared,
        flags: null, // set below (lazy require, defensive)
        manifest,
        argRest: process.argv.slice(3),
      };
      try { ctx.flags = require('./lib/flags'); } catch (e) { failOpenLog('runner flags lib', e); }

      for (const group of groups) {
        if (!matcherHits(group.matcher, toolName)) continue;
        for (const ruleName of group.rules || []) {
          let mod;
          try {
            mod = require(path.join(HOME_DIR, 'rules', ruleName + '.js'));
          } catch (e) {
            failOpenLog(`rule load ${ruleName}`, e);
            process.stderr.write(`[Hook][fail-open] rule '${ruleName}' failed to load — gate inactive, see fail-open log.\n`);
            continue;
          }
          try {
            const res = mod.check(ctx);
            if (res && Array.isArray(res.warn)) {
              for (const ln of res.warn) process.stderr.write(ln + '\n');
            }
            if (res && Array.isArray(res.block) && res.block.length) {
              blocks.push(...res.block);
            }
          } catch (e) {
            failOpenLog(`rule ${ruleName}`, e);
            process.stderr.write(`[Hook][fail-open] rule '${ruleName}' crashed — gate inactive for this call, see fail-open log.\n`);
          }
        }
      }
    } catch (e) {
      failOpenLog('runner', e);
      blocks = []; // runner-level failure NEVER blocks
    }

    if (blocks.length) {
      for (const ln of blocks) process.stderr.write(ln + '\n');
      // flush-guarded exit(2) — required on Windows pipes
      process.stderr.write('', () => process.exit(2));
      return;
    }
    process.stdout.write(d);
  });
}

main();
