if ( ! defined( 'ABSPATH' ) ) {
	exit; // No direct access.
}

define( 'AWORACLE_VERSION', '0.5.1' );
define( 'AWORACLE_DIR', plugin_dir_path( __FILE__ ) );
define( 'AWORACLE_URL', plugin_dir_url( __FILE__ ) );
define( 'AWORACLE_FILE', __FILE__ );

/**
 * Minimal PSR-4 autoloader for AwareWave\Oracle\* -> includes/ (same pattern as aware-wave-wp-bridge):
 * no composer at runtime, so the plugin loads standalone on any WordPress.
 */
spl_autoload_register(
	function ( $class ) {
		$prefix = 'AwareWave\\Oracle\\';
		if ( strpos( $class, $prefix ) !== 0 ) {
			return;
		}
		$relative = substr( $class, strlen( $prefix ) );
		$path     = AWORACLE_DIR . 'includes/' . str_replace( '\\', '/', $relative ) . '.php';
		if ( is_file( $path ) ) {
			require $path;
		}
	}
);

// Member-pseudonym salt: created on activation, or on first use if activation never ran (Options::salt).
// The site key is generated by the admin on purpose (or set as AWORACLE_SITE_KEYPAIR in wp-config.php).
// Member tables: created on activation, and on any later request where the schema version differs
// (plugin updated in place, network-activated sites, activation hook skipped).
register_activation_hook(
	__FILE__,
	function () {
		Settings\Options::activate();
		Members\Store::install();
	}
);
add_action( 'plugins_loaded', array( Members\Store::class, 'maybeInstall' ) );
register_deactivation_hook( __FILE__, array( Members\Store::class, 'unschedule' ) );

add_action(
	'init',
	function () {
		load_plugin_textdomain( 'aware-wave-oracle', false, dirname( plugin_basename( AWORACLE_FILE ) ) . '/languages' );
	}
);

// Settings screen: embed mode, engine addresses, site key (generate / rotate), locale and page maps, pseudonym salt.
