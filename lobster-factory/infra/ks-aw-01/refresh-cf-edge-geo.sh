#!/usr/bin/env bash
# Regenerate /etc/nginx/conf.d/cf-edge-geo.conf from Cloudflare's published edge
# ranges. This map is the origin-lockdown guard for every CF-proxied vhost on
# ks-aw-01 (snippets/cf-only.conf returns 403 unless the raw TCP peer is here).
#
# Replaces the SG-era ipset refresh (cf-origin-lockdown.sh --refresh): the
# 2026-08-28 consolidation moved the lockdown from iptables/ipset to an nginx
# geo map, so the refresh target moved with it.
#
# Safety: a truncated/failed fetch must never SHRINK the guard (that would 403
# legitimate CF edges) -- plausibility floor below, plus config-test rollback.
set -euo pipefail
GEO=/etc/nginx/conf.d/cf-edge-geo.conf
V4=$(curl -fsS --max-time 20 https://www.cloudflare.com/ips-v4)
V6=$(curl -fsS --max-time 20 https://www.cloudflare.com/ips-v6)
c4=$(printf '%s\n' "$V4" | grep -c .)
c6=$(printf '%s\n' "$V6" | grep -c .)
if [[ "$c4" -lt 10 || "$c6" -lt 5 ]]; then
  echo "FATAL: implausible CF list (v4=$c4 v6=$c6) - refusing to regenerate the guard"
  exit 1
fi
TMP=$(mktemp)
{ echo "# CF-edge-only guard map. REGENERATED by refresh-cf-edge-geo.sh - do not hand-edit."
  echo "# Source: cloudflare.com/ips-v4 + ips-v6, fetched $(date -u +%FT%TZ)"
  echo "geo \$realip_remote_addr \$cf_edge {"
  echo "    default 0;"
  echo "    127.0.0.1 1;"
  printf '%s\n' "$V4" "$V6" | grep . | sed 's/^/    /; s/$/ 1;/'
  echo "}"
} > "$TMP"
BAK=$(mktemp)
cp "$GEO" "$BAK"
install -m 0644 "$TMP" "$GEO"
if ! nginx -t 2>/dev/null; then
  cp "$BAK" "$GEO"
  nginx -t >/dev/null
  echo "FATAL: new geo map failed nginx -t; previous map restored"
  exit 1
fi
systemctl reload nginx
rm -f "$TMP" "$BAK"
echo "cf-edge-geo refreshed: v4=$c4 v6=$c6"
