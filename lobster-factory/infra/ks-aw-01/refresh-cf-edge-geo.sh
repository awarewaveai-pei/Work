#!/usr/bin/env bash
# Regenerate both Cloudflare-range files on ks-aw-01 from ONE fetch of Cloudflare's
# published edge ranges, so the two can never drift apart:
#   conf.d/cf-edge-geo.conf -- origin-lockdown guard for every CF-proxied vhost
#                              (snippets/cf-only.conf returns 403 unless the raw TCP peer is here)
#   conf.d/cf-realip.conf   -- set_real_ip_from list; real_ip_header stays in soulful-security.conf.
#                              A stale list fails silently (logs CF's IP, poisons fail2ban/LLAR).
#
# Replaces the SG-era ipset refresh (cf-origin-lockdown.sh --refresh): the
# 2026-08-28 consolidation moved the lockdown from iptables/ipset to an nginx
# geo map, so the refresh target moved with it.
#
# Safety: a truncated/failed fetch must never SHRINK the guard (that would 403
# legitimate CF edges) -- plausibility floor below, plus config-test rollback.
set -euo pipefail
GEO=/etc/nginx/conf.d/cf-edge-geo.conf
REALIP=/etc/nginx/conf.d/cf-realip.conf
# One run at a time: overlapping runs could pair fetch A's GEO with fetch B's REALIP.
exec 9>/run/refresh-cf-edge-geo.lock
flock -n 9 || { echo "FATAL: another refresh-cf-edge-geo.sh is running"; exit 1; }
V4=$(curl -fsS --max-time 20 https://www.cloudflare.com/ips-v4)
V6=$(curl -fsS --max-time 20 https://www.cloudflare.com/ips-v6)
c4=$(printf '%s\n' "$V4" | grep -c .)
c6=$(printf '%s\n' "$V6" | grep -c .)
if [[ "$c4" -lt 10 || "$c6" -lt 5 ]]; then
  echo "FATAL: implausible CF list (v4=$c4 v6=$c6) - refusing to regenerate the guard"
  exit 1
fi
STAMP="# Source: cloudflare.com/ips-v4 + ips-v6, fetched $(date -u +%FT%TZ)"
TMP_GEO=$(mktemp); TMP_REALIP=$(mktemp)
{ echo "# CF-edge-only guard map. REGENERATED by refresh-cf-edge-geo.sh - do not hand-edit."
  echo "$STAMP"
  echo "geo \$realip_remote_addr \$cf_edge {"
  echo "    default 0;"
  echo "    127.0.0.1 1;"
  printf '%s\n' "$V4" "$V6" | grep . | sed 's/^/    /; s/$/ 1;/'
  echo "}"
} > "$TMP_GEO"
{ echo "# CF real-IP trust list. REGENERATED by refresh-cf-edge-geo.sh - do not hand-edit."
  echo "$STAMP"
  printf '%s\n' "$V4" "$V6" | grep . | sed 's/^/set_real_ip_from /; s/$/;/'
} > "$TMP_REALIP"
BAK_GEO=$(mktemp); BAK_REALIP=$(mktemp)
cp "$GEO" "$BAK_GEO"
had_realip=0; [[ -f "$REALIP" ]] && { cp "$REALIP" "$BAK_REALIP"; had_realip=1; }
# Any failure from here on (install or nginx -t) restores BOTH files: never a half-updated pair.
restore() {
  cp "$BAK_GEO" "$GEO"
  if [[ "$had_realip" == 1 ]]; then cp "$BAK_REALIP" "$REALIP"; else rm -f "$REALIP"; fi
  echo "FATAL: CF file regeneration failed; previous files restored"
}
trap restore ERR
install -m 0644 "$TMP_GEO" "$GEO"
install -m 0644 "$TMP_REALIP" "$REALIP"
nginx -t 2>/dev/null
trap - ERR
systemctl reload nginx
rm -f "$TMP_GEO" "$TMP_REALIP" "$BAK_GEO" "$BAK_REALIP"
echo "cf-edge-geo refreshed: v4=$c4 v6=$c6"
