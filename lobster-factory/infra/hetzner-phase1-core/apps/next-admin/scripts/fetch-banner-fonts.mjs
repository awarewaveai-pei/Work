// Self-hosts the Banner tool's fonts (all SIL OFL 1.1) under public/banner-fonts/: Google Fonts' unicode-range slices
// (a CJK family is ~100 small woff2 files; the browser fetches only the slices a design uses), one fonts.css that
// points at them, and each family's OFL.txt. Re-run to refresh: node scripts/fetch-banner-fonts.mjs (from next-admin).
// Nothing is fetched from a CDN at runtime.
import fs from "node:fs";
import path from "node:path";
import crypto from "node:crypto";
import { fileURLToPath } from "node:url";

// family (css2 query) | google/fonts ofl/<dir>
const FAMILIES = [
  ["Noto Sans TC", "wght@100..900", "notosanstc"],
  ["Noto Serif TC", "wght@200..900", "notoseriftc"],
  ["LXGW WenKai TC", "wght@300;400;700", "lxgwwenkaitc"],
  ["Huninn", "", "huninn"],
  ["Inter", "wght@100..900", "inter"],
  ["Montserrat", "wght@100..900", "montserrat"],
  ["Playfair Display", "wght@400..900", "playfairdisplay"],
  ["Oswald", "wght@200..700", "oswald"],
  ["Bebas Neue", "", "bebasneue"],
];
const UA = "Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/130.0 Safari/537.36";
const OUT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "../public/banner-fonts");
// everything is fetched into TMP first and swapped in only when all of it arrived (a half download never replaces the set)
const TMP = `${OUT}.tmp`;

async function get(url, binary) {
  for (let i = 0; i < 4; i++) {
    try {
      const r = await fetch(url, { headers: { "User-Agent": UA }, signal: AbortSignal.timeout(30_000) });
      if (r.ok) return binary ? Buffer.from(await r.arrayBuffer()) : r.text();
    } catch {
      /* network error / timeout: retry */
    }
    await new Promise((res) => setTimeout(res, 1000 * (i + 1)));
  }
  throw new Error(`fetch failed: ${url}`);
}

fs.rmSync(TMP, { recursive: true, force: true });
fs.mkdirSync(TMP, { recursive: true });
let css = "/* Generated by scripts/fetch-banner-fonts.mjs -- do not edit. All families: SIL OFL 1.1 (see each OFL.txt). */\n";
for (const [family, axes, dir] of FAMILIES) {
  const q = family.replace(/ /g, "+") + (axes ? `:${axes}` : "");
  let src = await get(`https://fonts.googleapis.com/css2?family=${q}&display=swap`, false);
  const famDir = path.join(TMP, dir);
  fs.mkdirSync(famDir, { recursive: true });
  const urls = [...new Set(src.match(/https:\/\/fonts\.gstatic\.com\/[^)]+/g) ?? [])];
  for (const u of urls) {
    const buf = await get(u, true);
    const name = crypto.createHash("sha1").update(u).digest("hex").slice(0, 16) + ".woff2";
    fs.writeFileSync(path.join(famDir, name), buf);
    src = src.split(u).join(`/banner-fonts/${dir}/${name}`);
  }
  fs.writeFileSync(path.join(famDir, "OFL.txt"), await get(`https://raw.githubusercontent.com/google/fonts/main/ofl/${dir}/OFL.txt`, false));
  css += src.replace(/\/\* [^*]+ \*\/\n/g, "");
  console.log(`${family}: ${urls.length} files`);
}
fs.writeFileSync(path.join(TMP, "fonts.css"), css);
fs.rmSync(OUT, { recursive: true, force: true });
fs.renameSync(TMP, OUT);
